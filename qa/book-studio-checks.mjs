export default async function bookStudioChecks(page) {
  page.setDefaultTimeout(15000)
  const report={checks:[],errors:[]},check=(ok,name)=>{if(!ok)throw Error(name);report.checks.push(name)}
  page.on('pageerror',e=>report.errors.push(e.message))
  await page.setViewportSize({width:1810,height:1040})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('http://127.0.0.1:5175')
  await page.getByRole('button',{name:'Начать с нуля',exact:true}).click()
  const readings=await page.evaluate(async()=>(await import('/src/data/pythonCourse.ts')).pythonLessons.map(l=>l.reading))
  check(readings.length===24&&readings.every(r=>r.explanation.length>100&&r.walkthrough.length===3&&r.experiment&&r.answer&&r.source),'all 24 lessons have original book-guided reading and experiments')
  await page.locator('.syllabus button').nth(3).click()
  check((await page.locator('.book-source').innerText()).includes('§15.1'),'input lesson points to the relevant book section')
  check(await page.locator('.theory-copy>p').first().evaluate(e=>parseFloat(getComputedStyle(e).fontSize))>=18,'desktop theory text at least 18px')
  await page.locator('.book-experiment summary').click()
  check((await page.locator('.book-experiment details').innerText()).includes('710'),'experiment has a reasoned answer')
  await page.getByRole('button',{name:'Посмотреть выполнение примера',exact:false}).click()
  await page.locator('.stage-step').waitFor()
  check(await page.locator('.stage-mode').innerText()==='Учебный пример','preview is clearly distinguished from the student programme')
  check(await page.getByRole('textbox',{name:'Код решения'}).inputValue()==='value = input()\n# Преобразуй и посчитай\n','preview preserves student draft')
  check(await page.locator('.python-checks').count()===0,'preview cannot complete a lesson')
  check(await page.getByRole('button',{name:'Воспроизвести разбор',exact:true}).count()===1,'reduced motion disables automatic playback')
  check(await page.locator('.stage-controls>span').innerText()==='1 / 3','preview starts at first step')
  await page.getByRole('button',{name:'Следующий шаг',exact:true}).click()
  check((await page.locator('.stage-memory').innerText()).includes('number'),'single step reveals converted variable')
  await page.getByRole('textbox',{name:'Код решения'}).fill('value = input()\nnumber = int(value)\nanswer = number + 10\nprint(answer)')
  await page.getByRole('textbox',{name:'Ввод для Python'}).fill('7')
  await page.getByRole('button',{name:'Запустить код',exact:true}).click()
  await page.locator('.stage-step').waitFor()
  await page.waitForFunction(()=>document.querySelector('.line-numbers .active-line')?.textContent==='01')
  check(await page.locator('.line-numbers .active-line').innerText()==='01','first line remains highlighted after preview replacement')
  check(await page.locator('.stage-mode').innerText()==='Твоя программа','student execution has its own playback')
  check((await page.locator('.stage-memory').innerText()).includes("'7'"),'input starts as a string')
  await page.getByRole('button',{name:'Следующий шаг',exact:true}).click()
  await page.getByRole('button',{name:'Следующий шаг',exact:true}).click()
  check((await page.locator('.stage-memory').innerText()).includes('17'),'third step computes 17')
  await page.waitForFunction(()=>document.querySelector('.line-numbers .active-line')?.textContent==='03')
  check(await page.locator('.line-numbers .active-line').innerText()==='03','editor highlights the observed source line')
  await page.getByRole('button',{name:'Следующий шаг',exact:true}).click()
  check((await page.locator('.stage-output').innerText()).includes('17'),'print transfers result to stage output')
  await page.getByRole('button',{name:'Повторить разбор',exact:true}).click()
  await page.getByRole('button',{name:'Приостановить разбор',exact:true}).click()
  const frozen=await page.locator('.stage-controls>span').innerText();await page.waitForTimeout(1300)
  check(await page.locator('.stage-controls>span').innerText()===frozen,'pause freezes the timeline')
  await page.getByLabel('Скорость разбора').selectOption('2')
  await page.getByRole('button',{name:'Воспроизвести разбор',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.stage-controls>span').textContent==='4 / 4')
  check(true,'replay reaches last step at selected speed')
  const sound=await page.evaluate(async()=>{
    const {LofiEngine,musicTracks}=await import('/src/audio/lofi.ts')
    let selected='';const engine=new LofiEngine(id=>selected=id);engine.setVolume(.2);await engine.play()
    const ctx=engine.context,analyser=ctx.createAnalyser();engine.master.connect(analyser)
    await new Promise(r=>setTimeout(r,500));const values=new Float32Array(analyser.fftSize);analyser.getFloatTimeDomainData(values);const peak=Math.max(...values.map(Math.abs))
    engine.tick=512;engine.nextTime=ctx.currentTime;engine.schedule();const advanced=selected
    engine.setMood('ambient');const ambient=selected
    engine.pause();await new Promise(r=>setTimeout(r,800));analyser.getFloatTimeDomainData(values);const silent=Math.max(...values.map(Math.abs))
    analyser.disconnect();await engine.dispose();return {peak,silent,advanced,ambient,count:musicTracks.length}
  })
  check(sound.peak>.00001&&sound.silent<.00001,'music produces audio and pause becomes silent')
  check(sound.count===6&&sound.advanced==='rain'&&sound.ambient==='bay','six compositions, automatic advance and ambient selection')
  await page.locator('.music-dock summary').click()
  await page.getByLabel('Выбрать мелодию').selectOption('tram')
  check((await page.locator('.lofi-meta').innerText()).includes('84 BPM'),'track selection changes composition and tempo')
  await page.getByRole('button',{name:'Следующая мелодия'}).click()
  check(await page.getByLabel('Выбрать мелодию').inputValue()==='lanterns','next track works')
  await page.getByRole('button',{name:'Случайная мелодия'}).click()
  check(await page.getByLabel('Выбрать мелодию').inputValue()!=='lanterns','shuffle selects another composition')
  await page.locator('.music-dock summary').click()
  await page.setViewportSize({width:390,height:844})
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile practice has no horizontal overflow')
  check(await page.getByRole('textbox',{name:'Код решения'}).evaluate(e=>parseFloat(getComputedStyle(e).fontSize))>=15,'mobile code remains readable')
  await page.locator('.workshop-canvas').scrollIntoViewIfNeeded()
  await page.locator('.workshop-canvas canvas').evaluate(c=>c.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
  await page.locator('.workshop-fallback').waitFor()
  check(await page.locator('.stage-memory').isVisible(),'WebGL loss preserves textual execution state')
  check(report.errors.length===0,'no uncaught errors in upgraded studio')
  return report
}
