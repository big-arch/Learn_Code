export default async function adventureChecks(page) {
  // Caller creates a fresh context. No user storage is cleared.
  page.setDefaultTimeout(15000)
  const report={checks:[],errors:[]},check=(value,name)=>{if(!value)throw Error(name);report.checks.push(name)}
  page.on('pageerror',e=>report.errors.push(e.message))
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('http://127.0.0.1:5175')
  await page.getByRole('button',{name:'Отправиться на остров',exact:false}).click()
  await page.locator('.island-canvas canvas').waitFor()
  check(await page.locator('.island-canvas canvas').evaluate(c=>c.width>=c.clientWidth*1.4),'world renders above CSS resolution')
  check(await page.locator('.npc-world-label').first().innerText()==='! Мира','native text marks the next resident')
  const coords=()=>page.locator('.island-minimap>svg circle').last().evaluate(e=>[Number(e.getAttribute('cx')),Number(e.getAttribute('cy'))])
  const before=await coords()
  await page.locator('.island-canvas').focus()
  await page.keyboard.down('ArrowUp');await page.waitForTimeout(450);await page.keyboard.up('ArrowUp');await page.waitForTimeout(160)
  const after=await coords()
  check(Math.hypot(after[0]-before[0],after[1]-before[1])>.2,'keyboard moves actual hero')
  const quests=await page.evaluate(async()=> (await import('/src/data/adventure.ts')).islandQuests)
  await page.getByRole('button',{name:'Идти к цели',exact:true}).click()
  for(let i=0;i<quests.length;i++) {
    const q=quests[i]
    await page.locator('#island-quest-title').filter({hasText:q.name}).waitFor()
    check(true,'guided travel opens dialogue: '+q.npc)
    await page.getByRole('button',{name:'Написать код',exact:true}).click()
    if(i===0) {
      await page.getByRole('textbox',{name:'Код решения'}).fill('print(2+2)')
      await page.getByRole('button',{name:'Запустить код',exact:true}).click()
      await page.locator('.quest-result').waitFor()
      check(await page.locator('.quest-victory').count()===0,'wrong code cannot change island')
      const stationary=await coords()
      await page.getByRole('textbox',{name:'Код решения'}).press('ArrowUp')
      check(JSON.stringify(await coords())===JSON.stringify(stationary),'editing code pauses movement')
      await page.getByRole('button',{name:'Вернуться на остров',exact:true}).click()
      check(await page.locator('.island-story').count()===0,'closing unfinished dialogue does not produce success event')
      await page.getByRole('button',{name:'Идти к цели',exact:true}).click()
      await page.getByRole('button',{name:'Написать код',exact:true}).click()
    }
    await page.getByRole('textbox',{name:'Код решения'}).fill(i===0?'print("привет")':q.solution)
    await page.getByRole('button',{name:'Запустить код',exact:true}).click()
    await page.locator('.quest-victory').waitFor()
    check((await page.locator('.quest-victory').innerText()).includes(q.reward),'quest awarded immediately: '+q.id)
    const earned=await page.evaluate(()=>JSON.parse(localStorage.getItem('code-arena-progress-v1')).completed.length)
    check(earned===i+1,'completion saved without apply button: '+q.id)
    // X after success must also reveal the story; it must never lose a reward.
    await page.getByRole('button',{name:i===1?'Вернуться на остров':'Продолжить приключение',exact:true}).click()
    await page.getByRole('region',{name:'Продолжение истории'}).waitFor()
    check((await page.locator('.island-story').innerText()).includes(q.effect),'visible consequence: '+q.id)
    if(i===0) {
      check(await page.locator('.map-locked').count()===0,'map unlocked by first programme')
      check((await page.locator('.island-inventory').innerText()).includes('Искра с тобой'),'companion reward appears')
      await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250)
      const button=page.getByRole('button',{name:'Идти к Тиму',exact:false})
      await button.scrollIntoViewIfNeeded()
      check(await button.evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=70&&r.bottom<=innerHeight-64}),'mobile story continuation above navigation')
      check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile story has no horizontal overflow')
      await page.setViewportSize({width:1440,height:1000})
    }
    if(i<3)await page.getByRole('button',{name:'Идти к '+['','Тиму','Бобу','Лее'][i+1],exact:false}).click()
  }
  await page.getByRole('button',{name:'Исследовать самостоятельно',exact:true}).click()
  check((await page.locator('.island-objective').innerText()).includes('Маяк зажжён'),'beacon finale reached by traversing gate and bridge')
  const position=await coords();check(position[0]>5,'hero really crossed river')
  const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('code-arena-progress-v1')))
  check(state.xp===310&&state.completed.length===4,'four quests give 310 XP and do not complete course lessons')
  await page.getByRole('button',{name:'Лея: поговорить',exact:false}).click()
  await page.getByRole('button',{name:'Написать код',exact:true}).click()
  await page.getByRole('button',{name:'Запустить код',exact:true}).click()
  await page.locator('.quest-result').waitFor()
  check(await page.evaluate(()=>JSON.parse(localStorage.getItem('code-arena-progress-v1')).xp)===310,'replay cannot award XP again')
  await page.getByRole('button',{name:'Продолжить приключение',exact:true}).click()
  check(await page.locator('.island-story').count()===0,'replay does not repeat reward event')
  await page.getByText('Сохранено в SQL',{exact:true}).waitFor()
  const remote=await page.evaluate(async()=> (await(await fetch('/api/progress',{headers:{'X-Profile-Key':localStorage.getItem('code-arena-profile-key')}})).json()).progress)
  check(remote.completed.length===4&&remote.xp===310,'island quests persisted to SQLite')
  await page.reload()
  await page.locator('.side-nav').getByRole('button',{name:'Приключение',exact:true}).click()
  await page.getByText('4/4 жителей получили помощь',{exact:true}).waitFor()
  check(true,'world state restores after reload')
  await page.setViewportSize({width:390,height:844})
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile adventure has no horizontal overflow')
  await page.evaluate(()=>document.querySelector('.island-canvas canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
  await page.getByText('3D сейчас недоступно',{exact:true}).waitFor()
  await page.locator('.island-journal').getByRole('button',{name:'Открыть',exact:false}).first().click()
  await page.locator('.island-dialog').waitFor()
  check(true,'WebGL loss keeps quest dialogue accessible')
  check(report.errors.length===0,'no uncaught adventure errors')
  return report
}
