export default async function videoChecks(page) {
  page.setDefaultTimeout(20000)
  const report = { checks: [], errors: [] }
  const check = (value, label) => { if (!value) throw Error(label); report.checks.push(label) }
  page.on('pageerror', error => report.errors.push(error.message))
  await page.setViewportSize({ width: 1810, height: 1040 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('http://127.0.0.1:5175')
  await page.getByRole('button', { name: 'Начать с нуля', exact: true }).click()
  const data = await page.evaluate(async () => (await import('/src/data/python-video.json')).default)
  await page.locator('.video-course-sources>summary').click()
  check((await page.locator('.video-source-grid').innerText()).includes('расшифровка недоступна'), 'second course is not represented as a completed transcript analysis')
  await page.locator('.video-course-sources>summary').click()
  for (const lab of data.labs) {
    await page.locator('.syllabus button').nth(Number(lab.lessonId.slice(-2)) - 1).click()
    await page.locator('.video-lesson>summary').focus()
    await page.keyboard.press('Enter')
    const editor = page.locator('.video-lab textarea')
    await editor.fill(lab.solution)
    await page.locator('.video-lab').getByRole('button', { name: 'Запустить код', exact: true }).click()
    await page.getByText('Готово! Все проверки пройдены.', { exact: true }).waitFor()
    check(await page.locator('.video-checks .retry').count() === 0, lab.id + ': browser Python solution passes')
    check(await page.locator('.video-lab .stage-step').count() === 1, lab.id + ': real trace is displayed')
    check((await page.locator('.video-chapters a').first().getAttribute('href')).includes('&t='), lab.id + ': timestamp source link')
  }
  check(await page.evaluate(() => { const p = JSON.parse(localStorage.getItem('code-arena-progress-v1')); return p.xp === 0 && p.completed.length === 0 && Object.keys(p.drafts).length === 0 }), 'additional practice never modifies main progress or drafts')
  await page.locator('.syllabus button').nth(11).click()
  await page.locator('.video-lesson>summary').click()
  check(await page.locator('.video-lab textarea').inputValue() === data.labs.find(l => l.id === 'copy').solution, 'independent draft survives lesson navigation')
  await page.locator('.video-lab textarea').fill('while True: pass')
  await page.locator('.video-lab').getByRole('button', { name: 'Запустить код', exact: true }).click()
  await page.getByRole('button', { name: 'Остановить Python', exact: true }).click()
  await page.locator('.video-python-error').waitFor()
  check((await page.locator('.video-python-error').innerText()).includes('остановлено'), 'stop cancels Python')
  await page.locator('.video-lab textarea').fill('print(123)')
  await page.locator('.video-lab').getByRole('button', { name: 'Запустить код', exact: true }).click()
  await page.locator('.video-checks .retry').first().waitFor()
  check(await page.locator('.video-checks .retry').count() > 0, 'wrong answer gets actionable failed checks')
  await page.locator('.video-lesson>summary').click()
  await page.locator('.video-lesson>summary').click()
  await page.getByRole('button', { name: 'Показать пример в действии', exact: true }).click()
  await page.getByText('Вывод учебного примера', { exact: true }).waitFor()
  check(await page.locator('.video-lab textarea').inputValue() === 'print(123)', 'example playback preserves the draft')
  check(await page.locator('.video-checks').count() === 0, 'example playback does not grade student code')
  await page.locator('.video-lab-grid').screenshot({ path: 'qa/video-practice-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile has no horizontal overflow')
  check(await page.locator('.video-lab-copy>p').first().evaluate(e => parseFloat(getComputedStyle(e).fontSize)) >= 17, 'mobile copy is at least 17px')
  await page.locator('.video-lab-copy').screenshot({ path: 'qa/video-practice-mobile.png' })
  await page.locator('.video-lab textarea').fill('print("saved")')
  await page.reload()
  // Navigation is not stored; open the Python course again through the sidebar.
  await page.getByRole('button', { name: 'Начать с нуля', exact: true }).click()
  await page.locator('.syllabus button').nth(11).click()
  await page.locator('.video-lesson>summary').click()
  check(await page.locator('.video-lab textarea').inputValue() === 'print("saved")', 'draft survives reload')
  await page.locator('.video-lab textarea').fill('while True: pass')
  await page.locator('.video-lab').getByRole('button', { name: 'Запустить код', exact: true }).click()
  await page.locator('.syllabus button').nth(1).click()
  await page.locator('.video-lesson>summary').click()
  check(await page.locator('.video-lab textarea').inputValue() === data.labs[0].solution, 'running worker is disposed when changing lessons')
  check(report.errors.length === 0, 'no page errors')
  return report
}
