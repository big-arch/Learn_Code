export default async function publicBuildChecks(page, origin = 'https://big-arch.github.io/Learn_Code/') {
  page.setDefaultTimeout(20000)
  const report = {checks: [], errors: [], badResponses: [], apiRequests: []}
  const check = (ok,name) => {if(!ok)throw Error(name); report.checks.push(name)}
  page.on('pageerror', e => report.errors.push(e.message))
  page.on('response',r => {if(r.url().startsWith(origin) && r.status() >= 400)report.badResponses.push({url:r.url(),status:r.status()})})
  page.on('request',r => {if(r.url().includes('/api/progress'))report.apiRequests.push(r.url())})
  await page.goto(origin)
  await page.getByRole('button',{name:'Начать с нуля',exact:true}).click()
  await page.getByRole('tab',{name:'03 Написать код'}).click()
  await page.getByRole('textbox',{name:'Код решения'}).fill("print(\"Привет, космос!\")")
  await page.getByRole('button',{name:'Запустить код',exact:true}).click()
  await page.locator('.python-checks .passed').first().waitFor({timeout:60000})
  check(true,'Python Worker and interpreter run under repository subpath')
  await page.locator('.side-nav').getByRole('button',{name:'Мастерская',exact:true}).click()
  await page.getByRole('textbox',{name:'Код мастерской'}).fill('justify-content: flex-end;')
  await page.getByRole('button',{name:'Запустить код',exact:true}).click()
  await page.locator('.lab-feedback.success').waitFor()
  check(true,'CSS game completes')
  await page.reload()
  await page.locator('.side-nav').getByRole('button',{name:'Мастерская',exact:true}).click()
  check(await page.getByRole('textbox',{name:'Код мастерской'}).inputValue()==='justify-content: flex-end;','draft restored after reload')
  check(await page.evaluate(()=>JSON.parse(localStorage.getItem('code-arena-progress-v1')).completed.includes('lab-v1-flex-01')),'completion restored')
  await page.locator('.side-nav').getByRole('button',{name:'Прогресс',exact:true}).click()
  await page.getByText('Сохранено в этом браузере.',{exact:false}).waitFor()
  check(true,'browser storage status is explicit')
  await page.locator('.side-nav').getByRole('button',{name:'Приключение',exact:true}).click()
  await page.locator('.island-objective').waitFor()
  check(await page.locator('canvas').count()>0,'island renders')
  await page.setViewportSize({width:390,height:844})
  await page.locator('.mobile-nav').getByRole('button',{name:'Мастерская',exact:true}).click()
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'mobile workshop fits')
  check(report.errors.length===0,'no JS exceptions')
  check(report.badResponses.length===0,'no missing app assets')
  check(report.apiRequests.length===0,'static site never requests absent SQL API')
  return report
}
